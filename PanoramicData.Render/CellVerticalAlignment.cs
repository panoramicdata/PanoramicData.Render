namespace PanoramicData.Render;

/// <summary>
/// Specifies vertical alignment of content within a table cell.
/// </summary>
internal enum CellVerticalAlignment
{
	/// <summary>
	/// Content is aligned to the top of the cell (default).
	/// </summary>
	Top = 0,

	/// <summary>
	/// Content is vertically centered in the cell.
	/// </summary>
	Center = 1,

	/// <summary>
	/// Content is aligned to the bottom of the cell.
	/// </summary>
	Bottom = 2,
}
